// Package timeline owns explicit agent work records. It never collects conversations,
// invokes agents, or treats a Markdown checkbox line as a durable task identity.
package timeline

import (
	"encoding/json"
	"errors"
)

const SchemaVersion = 1
const MaxDocumentBytes = 8 << 20
const MaxEvents = 10000
const MaxTasks = 1000

var (
	ErrNotFound  = errors.New("timeline project not found")
	ErrConflict  = errors.New("timeline revision conflict")
	ErrDuplicate = errors.New("timeline event identity reused with different content")
	ErrInvalid   = errors.New("invalid timeline record")
	ErrLimit     = errors.New("timeline storage limit reached")
)

// Request is an explicitly submitted mutation. ExpectedRevision is required even
// for append-only annotations; an identical source/event_id retry is exempt.
type Request struct {
	Source           string          `json:"source"`
	EventID          string          `json:"event_id"`
	ExpectedRevision uint64          `json:"expected_revision"`
	Kind             string          `json:"kind"`
	Payload          json.RawMessage `json:"payload"`
}

type Event struct {
	Sequence uint64          `json:"sequence"`
	At       string          `json:"at"`
	Source   string          `json:"source"`
	EventID  string          `json:"event_id"`
	Kind     string          `json:"kind"`
	Payload  json.RawMessage `json:"payload"`
}

type Project struct {
	Title       string `json:"title"`
	Description string `json:"description,omitempty"`
	NoteID      int64  `json:"note_id,omitempty"`
	Mode        string `json:"mode"` // serial or parallel root scheduling
}

type Task struct {
	ID               string  `json:"id"`
	ParentID         string  `json:"parent_id,omitempty"`
	Title            string  `json:"title"`
	Detail           string  `json:"detail,omitempty"`
	Status           string  `json:"status"`
	Owner            string  `json:"owner,omitempty"`
	Priority         *int    `json:"priority,omitempty"` // 0 through 3; null is unprioritized
	Weight           float64 `json:"weight"`
	DoneMinutes      float64 `json:"done_minutes"`
	RemainingMinutes float64 `json:"remaining_minutes"`
	Mode             string  `json:"mode"` // serial or parallel children
}

// Report is supplied by an author, not generated by Track. EventSequences identify
// the records it summarizes; period timestamps must be RFC3339, start <= end.
type Report struct {
	ID             string   `json:"id"`
	TaskID         string   `json:"task_id,omitempty"`
	Author         string   `json:"author"`
	PeriodStart    string   `json:"period_start"`
	PeriodEnd      string   `json:"period_end"`
	Summary        string   `json:"summary"`
	Uncertainty    string   `json:"uncertainty,omitempty"`
	UserAction     string   `json:"user_action,omitempty"`
	EventSequences []uint64 `json:"event_sequences"`
}

type Discussion struct {
	ID         string `json:"id"`
	TargetType string `json:"target_type"` // project, task, report
	TargetID   string `json:"target_id"`
	Author     string `json:"author"`
	Text       string `json:"text"`
}

// Control is a cooperative request ledger. Acknowledgements and results are
// caller reports, not proof that Track stopped or resumed a process.
type Control struct {
	ID     string `json:"id"`
	TaskID string `json:"task_id"`
	Owner  string `json:"owner"`
	Action string `json:"action"` // pause or resume
	Status string `json:"status"` // requested, acknowledged, completed, rejected, failed
	Result string `json:"result,omitempty"`
}

type ControlUpdate struct {
	ID     string `json:"id"`
	Status string `json:"status"`
	Result string `json:"result,omitempty"`
}

type Progress struct {
	Fraction         float64 `json:"fraction"`
	DoneMinutes      float64 `json:"done_minutes"`
	RemainingMinutes float64 `json:"remaining_minutes"`
	Total            int     `json:"total"`
	Done             int     `json:"done"`
	Retired          int     `json:"retired"`
}

type Snapshot struct {
	SchemaVersion int    `json:"schema_version"`
	ProjectID     string `json:"project_id"`
	Project
	Revision    uint64       `json:"revision"`
	Tasks       []Task       `json:"tasks"`
	Reports     []Report     `json:"reports"`
	Discussions []Discussion `json:"discussions"`
	Controls    []Control    `json:"controls"`
	Events      []Event      `json:"events"`
	Progress    Progress     `json:"progress"`
	// TaskProgress is derived from each task subtree, never accepted as input.
	TaskProgress map[string]Progress `json:"task_progress"`
}

type Summary struct {
	ProjectID string   `json:"project_id"`
	Title     string   `json:"title"`
	NoteID    int64    `json:"note_id,omitempty"`
	Revision  uint64   `json:"revision"`
	Progress  Progress `json:"progress"`
}
